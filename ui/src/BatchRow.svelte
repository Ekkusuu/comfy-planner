<script>
  // A batch in the queue: the jobs one request made, as one collapsible row with done/total progress.
  // Used on Queue (full) and in Plan's side queue. Expanding lists its jobs; the actions apply to the whole batch.
  import Icon from './Icon.svelte'
  import LivePreview from './LivePreview.svelte'
  import { api } from './api.js'
  import { live, batchThumb, imageTotals, workflowTitle, jobTitle, clip } from './store.svelte.js'

  let { batch, full = false, stage = false, grip = false, first = false, last = false, oncancel, onretry, onclear, onmove, onopen, class: cls = '', ...rest } = $props()

  let open = $state(stage) // the stage has room beside the picture, so its job list starts open
  const jobs = $derived(batch.jobs)
  const running = $derived(jobs.some((j) => j.status === 'running'))
  const waiting = $derived(jobs.some((j) => j.status === 'queued'))
  const active = $derived(running || waiting)
  const failed = $derived(jobs.filter((j) => j.status === 'failed').length)
  const stopped = $derived(jobs.filter((j) => j.status === 'cancelled').length)
  const totals = $derived(imageTotals(jobs))
  const partial = $derived.by(() => {
    const j = jobs.find((x) => x.status === 'running')
    return j ? (live.progress[j.id]?.frac ?? 0) : 0
  })
  const pct = $derived(Math.min(100, Math.round(((totals.done + partial) / Math.max(totals.total, 1)) * 100)))
  const thumb = $derived(batchThumb(jobs))

  // Live look at the image being generated by the batch's running job (same as QueueRow), swapped in once it has loaded.
  const runningId = $derived(jobs.find((j) => j.status === 'running')?.id ?? null)
  let frame = $state(null) // { job, url } of the newest preview that has loaded
  $effect(() => {
    const id = runningId
    const number = id != null ? live.preview[id] : null
    if (!number) return
    const url = api.previewUrl(id, number)
    const img = new Image()
    let stale = false
    img.onload = () => { if (!stale) frame = { job: id, url } }
    img.src = url
    return () => { stale = true }
  })
  const showFrame = $derived(!!frame && frame.job === runningId && !!live.preview[runningId])
  const title = $derived(batch.request || 'Batch')
  const line = $derived.by(() => {
    const parts = [`${totals.done} of ${totals.total} images`]
    if (failed) parts.push(`${failed} failed`)
    if (stopped) parts.push(`${stopped} cancelled`)
    if (!active && !failed && !stopped) parts[0] = `${totals.total} images`
    if (full && jobs[0]?.workflow_id) parts.push(workflowTitle(jobs[0].workflow_id))
    return parts.join(' · ')
  })
  const STATE = { queued: 'Waiting', running: 'Running', done: 'Done', failed: 'Failed', cancelled: 'Cancelled' }
</script>

<div class="q bx {cls}" class:running class:stage {...rest}>
  {#if stage}
    <LivePreview jobId={runningId} scope={`batch-${batch.key}`} />
  {:else if showFrame}
    <img class="thumb" src={frame.url} alt="" decoding="async" />
  {:else if thumb}
    <img class="thumb" src={api.thumbUrl(thumb.id, 128)} alt="" loading="lazy" decoding="async" />
  {:else}
    <span class="thumb ph"><Icon name="image" /></span>
  {/if}
  <div class="bx-main">
    <button class="bx-title" aria-expanded={open} title={title} onclick={() => (open = !open)}>
      <span class="bx-chev" class:bx-open={open}><Icon name="chevron" /></span>{clip(title, stage ? 280 : 90)}
    </button>
    <div class="bx-line" class:bx-err={failed > 0 && !active} title={line}>{line}</div>
    {#if active || (pct > 0 && pct < 100)}
      <div class="prog" class:indet={running && totals.done === 0 && !partial} role="progressbar" aria-label="Batch progress" aria-valuenow={pct} aria-valuemin="0" aria-valuemax="100"><i style="width:{pct}%"></i></div>
    {/if}
  </div>
  <div class="acts">
    {#if full && waiting && !running && onmove}
      {#if grip}<span class="icon-btn sm grip" aria-hidden="true" title="Drag to reorder"><Icon name="grip" /></span>{/if}
      <button class="icon-btn sm" aria-label="Move up" disabled={first} onclick={(e) => { e.stopPropagation(); onmove(-1) }}><Icon name="up" /></button>
      <button class="icon-btn sm" aria-label="Move down" disabled={last} onclick={(e) => { e.stopPropagation(); onmove(1) }}><span style="display:grid;transform:rotate(180deg)"><Icon name="up" /></span></button>
    {/if}
    {#if !active && (failed || stopped) && onretry}
      <button class="icon-btn" aria-label="Retry the failed images" title="Retry" onclick={(e) => { e.stopPropagation(); onretry(batch) }}><Icon name="retry" /></button>
    {/if}
    {#if !active && onclear}
      <button class="icon-btn" aria-label="Clear from the queue" title="Clear from the queue" onclick={(e) => { e.stopPropagation(); onclear(batch) }}><Icon name="x" /></button>
    {/if}
    {#if active && oncancel}
      <button class="icon-btn" aria-label="Cancel the rest of the batch" title="Cancel the rest" onclick={(e) => { e.stopPropagation(); oncancel(batch) }}><Icon name="x" /></button>
    {/if}
  </div>
  {#if open}
    <ul class="bx-jobs">
      {#each jobs as job (job.id)}
        <li class="bx-job">
          <span class="bx-dot bx-{job.status}"></span>
          {#if onopen && job.image_counts?.done}
            <button class="bx-jtext bx-link" title={jobTitle(job)} onclick={() => onopen(job)}>{jobTitle(job)}</button>
          {:else}
            <span class="bx-jtext" title={jobTitle(job)}>{jobTitle(job)}</span>
          {/if}
          <span class="bx-jstate">{job.count > 1 ? `${job.count} images · ` : ''}{STATE[job.status] ?? job.status}</span>
        </li>
      {/each}
    </ul>
  {/if}
</div>

